import {strict as assert} from 'node:assert';
import {readFileSync} from 'node:fs';
import {exactSlotMatches, filledAnswerBoard, expectedSequence} from '../src/utils/answer.ts';
import {resumeLevelIndex} from '../src/utils/progress.ts';
import {newRail, insertFromPool, moveByInsertion, takeBack} from '../src/utils/railState.ts';
const levels=JSON.parse(readFileSync(new URL('../src/data/allLevels.json',import.meta.url),'utf8'));
const level=levels[0];
const words=level.words;
const board=newRail(words, xs=>xs);
assert.deepEqual(exactSlotMatches(board.slots,level), Array(words.length).fill(false));
let state=insertFromPool(board,4,words[4].id);
assert.equal(exactSlotMatches(state.slots,level)[4],true,'slot 5 is green, even if slots 1-4 empty');
assert.equal(exactSlotMatches(state.slots,level).filter(Boolean).length,1);
state=insertFromPool(state,1,words[5].id);
assert.equal(exactSlotMatches(state.slots,level)[1],false,'wrong slot is not green');
state=moveByInsertion(state,1,6,'before');
assert.equal(state.slots.filter(Boolean).length,2,'reordering does not lose words');
state=takeBack(state,4);
assert.equal(exactSlotMatches(state.slots,level)[4],false,'green must vanish on return');
let answer=filledAnswerBoard(state,level);
assert.equal(answer.pool.length,0);
assert.deepEqual(answer.slots.map(w=>w.text),level.correctSequence,'all words align, including repeated I');
assert.equal(exactSlotMatches(answer.slots,level).filter(Boolean).length,words.length);
const v8={currentLevelIndex:0,completedLevelIds:levels.slice(0,16).map(l=>l.id),progressVersion:2};
assert.equal(resumeLevelIndex(v8,levels),16,'migrate V8 stuck at first lesson to LEVEL 17');
assert.equal(resumeLevelIndex({...v8,progressVersion:3},levels),0,'V9 explicit user cursor is preserved');
assert.equal(resumeLevelIndex({currentLevelIndex:16,completedLevelIds:[],progressVersion:3},levels),16,'manual jump persists');
assert.deepEqual(expectedSequence(level),level.correctSequence);
console.log('PASS: correct-slot feedback, insertion, duplicates, autofill, and V8-to-V9 resume');
